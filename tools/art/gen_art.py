#!/usr/bin/env python3
"""Procedural pixel-art generator (source of truth for assets/sprites/*.png).

Usage: python3 tools/art/gen_art.py
Writes:
  assets/sprites/palette.png   palette swatch (for reviewers)
  assets/sprites/test_gear.png test sprite proving the pipeline
  config/palette.json          palette for runtime use (Config.get_cfg("palette"))
Afterwards run `godot --headless --path . --import`.
"""
import json
import math
import os
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import palette as pal  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SPRITES = os.path.join(ROOT, "assets", "sprites")


def check_palette(img: Image.Image, name: str) -> None:
    """Fail loudly if a sprite uses a color outside the palette."""
    allowed = {pal.rgb(n) for n in pal.names()}
    for _count, (r, g, b, a) in img.getcolors(maxcolors=1 << 16):
        if a and (r, g, b) not in allowed:
            raise SystemExit(f"{name}: color {(r, g, b)} is not in the palette")


def save(img: Image.Image, name: str) -> None:
    check_palette(img, name)
    path = os.path.join(SPRITES, name)
    img.save(path)
    print("wrote", os.path.relpath(path, ROOT))


def palette_swatch(cell: int = 24) -> Image.Image:
    ramps = list(pal.RAMPS.items())
    width = max(len(c) for _, c in ramps)
    img = Image.new("RGBA", (width * cell, len(ramps) * cell), pal.TRANSPARENT)
    d = ImageDraw.Draw(img)
    for row, (ramp, cols) in enumerate(ramps):
        for col in range(len(cols)):
            x0, y0 = col * cell, row * cell
            d.rectangle([x0, y0, x0 + cell - 1, y0 + cell - 1], fill=pal.rgba(f"{ramp}_{col}"))
    return img


def gear(size: int = 20, teeth: int = 8) -> Image.Image:
    """Brass gear with outline, light from top-left."""
    img = Image.new("RGBA", (size, size), pal.TRANSPARENT)
    px = img.load()
    c = (size - 1) / 2.0
    r_body, r_tooth, r_hole = size * 0.36, size * 0.49, size * 0.13
    for y in range(size):
        for x in range(size):
            dx, dy = x - c, y - c
            r = math.hypot(dx, dy)
            ang = math.atan2(dy, dx)
            tooth = math.cos(ang * teeth) > -0.1
            outer = r_tooth if tooth else r_body
            if r_hole < r <= outer:
                light = -(dx + dy) / (size * 0.7)  # top-left brighter
                if r > outer - 1.0 or r < r_hole + 1.0:
                    name = "brass_0"
                elif light > 0.3:
                    name = "brass_3"
                elif light > -0.2:
                    name = "brass_2"
                else:
                    name = "brass_1"
                px[x, y] = pal.rgba(name)
    return img


def export_palette_json() -> None:
    path = os.path.join(ROOT, "config", "palette.json")
    data = {"_comment": "Generated by tools/art/gen_art.py from tools/art/palette.py. Do not edit by hand.",
            "colors": pal.PALETTE,
            "ramps": {k: [f"{k}_{i}" for i in range(len(v))] for k, v in pal.RAMPS.items()}}
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("wrote", os.path.relpath(path, ROOT))


def main() -> None:
    os.makedirs(SPRITES, exist_ok=True)
    export_palette_json()
    save(palette_swatch(), "palette.png")
    save(gear(), "test_gear.png")


if __name__ == "__main__":
    main()
