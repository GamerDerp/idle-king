def contact_sheet(m: Manifest) -> Image.Image:
    items = [(n, f) for n, f in m.sheets if not n.startswith("battlefield_bg") and n != "steam_curtain"]
    pad, maxw = 4, 640
    x = y = pad
    rowh = 0
    pos = []
    for name, frames in items:
        w = sum(f.w for f in frames) + (len(frames) - 1) * 2
        h = frames[0].h
        if x + w + pad > maxw:
            x, y, rowh = pad, y + rowh + pad, 0
        pos.append((x, y, frames))
        x += w + pad * 2
        rowh = max(rowh, h)
    img = Image.new("RGBA", (maxw, y + rowh + pad), pal.rgba("dust_1"))
    for (x, y, frames) in pos:
        for f in frames:
            img.alpha_composite(f.img, (x, y))
            x += f.w + 2
    return upscale(img, 2)


