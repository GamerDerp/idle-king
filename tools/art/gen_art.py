def check_palette(img: Image.Image, name: str) -> None:
    """Fail loudly if an image uses a colour outside the palette (alpha may vary)."""
    allowed = {pal.rgb(n) for n in pal.names()}
    for _count, (r, g, b, a) in img.getcolors(maxcolors=1 << 20):
        if a and (r, g, b) not in allowed:
            raise SystemExit(f"{name}: color {(r, g, b)} is not in the palette")


def save(img: Image.Image, rel: str) -> None:
    check_palette(img, rel)
    path = os.path.join(SPRITES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)


class Manifest:
    def __init__(self):
        self.sprites = {}
        self.sheets = []   # (name, frames) for the contact sheet

    def add(self, category: str, name: str, frames, fps: float = 0, anchor=None, loop: bool = True,
            note: str = "") -> None:
        if isinstance(frames, Canvas):
            frames = [frames]
        rel = f"{category}/{name}.png"
        save(strip(frames), rel)
        w, h = frames[0].w, frames[0].h
        entry = {"file": f"res://assets/sprites/{rel}", "frame_size": [w, h], "frames": len(frames),
                 "fps": fps, "anchor": list(anchor) if anchor else [w // 2, h - 1], "loop": loop}
        if note:
            entry["note"] = note
        self.sprites[name] = entry
        self.sheets.append((name, frames))

    def write(self) -> None:
        data = {
            "_comment": "Generated by tools/art/gen_art.py. Do not edit by hand. Frames are laid out "
                        "horizontally; anchor is in frame pixels (feet / pivot). Art is shown at 'scale'.",
            "scale": L.SCALE,
            "battlefield": L.as_dict(),
            "sprites": dict(sorted(self.sprites.items())),
        }
        with open(os.path.join(SPRITES, "manifest.json"), "w", encoding="utf-8") as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
            f.write("\n")


