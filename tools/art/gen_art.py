#!/usr/bin/env python3
"""Procedural pixel-art generator: the single source of truth for all game art.

Usage: python3 tools/art/gen_art.py
Writes (deterministically):
  config/palette.json                   palette for runtime use (Config.color("brass_3"))
  assets/sprites/<category>/*.png       sprites and strips (1x art pixels, shown at 2x)
  assets/sprites/manifest.json          name -> file, frame size, frames, fps, anchor, loop
  assets/sprites/palette.png            palette swatch;  assets/sprites/test_gear.png (legacy test)
  fonts/kotel_{regular,bold,title}.fnt  BMFont pixel fonts (+ .png atlases)
  themes/ui/*.png, themes/main_theme.tres  UI skin (textures saved at 2x)
  docs/art/*.png                        reviewer sheets (font specimen, sprite contact sheet)
Every sprite is validated against the palette (tools/art/palette.py): any other colour fails the run.
Afterwards run `godot --headless --path . --import`.
"""
