def palette_swatch(cell: int = 24) -> Image.Image:
    ramps = list(pal.RAMPS.items())
    width = max(len(c) for _, c in ramps)
    img = Image.new("RGBA", (width * cell, len(ramps) * cell), pal.TRANSPARENT)
    d = ImageDraw.Draw(img)
    for row, (ramp, cols) in enumerate(ramps):
        for col in range(len(cols)):
            x0, y0 = col * cell, row * cell
            d.rectangle([x0, y0, x0 + cell - 1, y0 + cell - 1], fill=pal.rgba(f"{ramp}_{col}"))
    return img


def gear(size: int = 20, teeth: int = 8) -> Image.Image:
    """Brass gear with outline, light from top-left (used by the placeholder main scene)."""
    img = Image.new("RGBA", (size, size), pal.TRANSPARENT)
    px = img.load()
    c = (size - 1) / 2.0
    r_body, r_tooth, r_hole = size * 0.36, size * 0.49, size * 0.13
    for y in range(size):
        for x in range(size):
            dx, dy = x - c, y - c
            r = math.hypot(dx, dy)
            ang = math.atan2(dy, dx)
            tooth = math.cos(ang * teeth) > -0.1
            outer = r_tooth if tooth else r_body
            if r_hole < r <= outer:
                light = -(dx + dy) / (size * 0.7)
                if r > outer - 1.0 or r < r_hole + 1.0:
                    name = "brass_0"
                elif light > 0.3:
                    name = "brass_3"
                elif light > -0.2:
                    name = "brass_2"
                else:
                    name = "brass_1"
                px[x, y] = pal.rgba(name)
    return img


def export_palette_json() -> None:
    path = os.path.join(ROOT, "config", "palette.json")
    data = {"_comment": "Generated by tools/art/gen_art.py from tools/art/palette.py. Do not edit by hand.",
            "colors": pal.PALETTE,
            "ramps": {k: [f"{k}_{i}" for i in range(len(v))] for k, v in pal.RAMPS.items()}}
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


