"""Hand-drawn glyphs of the "Kotel" pixel font (regular weight).

Grid (rows, 0 = top of the line):
  0-1   accent area for capitals (Ё, Й)
  2-8   cap height 7 (baseline is the bottom of row 8)
  4-8   x-height 5
  9-10  descenders
Each entry: char -> (top_row, [row strings]); '#' = ink, '.' = empty.
The glyph width is the row length; advance = width + 1 (see font_gen.py).
"""

G = {}


def g(chars: str, top: int, rows: str) -> None:
    lines = [r for r in rows.split() if r]
    w = len(lines[0])
    for r in lines:
        assert len(r) == w, (chars, rows)
    for ch in chars:
        G[ch] = (top, lines)


